export function getOlympiaServerSpellId(olympiaSpellId: number): number | undefined {
    return OLYMPIA_TO_SERVER[olympiaSpellId];
}

/** Reverse map: multiplayer Spells.json id → Olympia Magic.cfg id (first match). */
const SERVER_TO_OLYMPIA: Readonly<Record<number, number>> = (() => {
    const rev: Record<number, number> = {};
    for (const [olympia, server] of Object.entries(OLYMPIA_TO_SERVER)) {
        const s = Number(server);
        if (rev[s] === undefined) {
            rev[s] = Number(olympia);
        }
    }
    return rev;
})();

export function getOlympiaSpellIdFromServer(serverSpellId: number): number | undefined {
    return SERVER_TO_OLYMPIA[serverSpellId];
}

export function isServerAuthoritativeOlympiaSpell(olympiaSpellId: number): boolean {
    return OLYMPIA_TO_SERVER[olympiaSpellId] !== undefined;
}
